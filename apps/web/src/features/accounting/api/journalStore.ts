import type { AuditEvent } from '@/features/accounting/data/access';
import type { JournalEntry } from '@/features/accounting/types';

/**
 * Demo-mode journal store shared by accounting.api (which assembles the
 * ledger) and accountingPro.api (workflow, closing, assets, bank…). With
 * Supabase connected this is journal_entries + journal_entry_lines, where the
 * same rules run in post_journal_entry / reverse_journal_entry (0057).
 *
 * Holds:
 *  - WORKFLOW: entries created in the journal screen (any status). Only the
 *    `posted` ones reach the ledger.
 *  - SYSTEM: auto entries generated by documents (disposals, transfers,
 *    allocations, closing, credit notes…) — always posted, idempotent by key.
 *  - AUDIT: append-only trail (no update/delete exported).
 */

const WORKFLOW: JournalEntry[] = [];
const SYSTEM: JournalEntry[] = [];
const AUDIT: AuditEvent[] = [];
let entrySeq = 5000;
let auditSeq = 0;

export function nextEntryIds(prefix = 'je-w'): { id: string; entry_no: number } {
  entrySeq += 1;
  return { id: `${prefix}-${entrySeq}`, entry_no: entrySeq };
}

export function workflowEntries(): JournalEntry[] {
  return WORKFLOW.map(clone);
}
export function systemEntries(): JournalEntry[] {
  return SYSTEM.map(clone);
}
/** Entries that belong in the ledger (posted only). */
export function postedStoreEntries(): JournalEntry[] {
  return [...SYSTEM, ...WORKFLOW].filter((e) => e.status === 'posted').map(clone);
}

export function findStoreEntry(id: string): JournalEntry | undefined {
  const e = WORKFLOW.find((x) => x.id === id) ?? SYSTEM.find((x) => x.id === id);
  return e ? clone(e) : undefined;
}

export function upsertWorkflow(entry: JournalEntry): JournalEntry {
  const i = WORKFLOW.findIndex((x) => x.id === entry.id);
  if (i >= 0) WORKFLOW[i] = clone(entry);
  else WORKFLOW.unshift(clone(entry));
  return clone(entry);
}

/** Add a system posting once per idempotency key / reference. Returns false if it existed. */
export function addSystemEntry(entry: JournalEntry): boolean {
  const key = entry.idempotency_key ?? entry.reference;
  if (key && SYSTEM.some((x) => (x.idempotency_key ?? x.reference) === key)) return false;
  SYSTEM.unshift(clone({ ...entry, status: 'posted' }));
  return true;
}

/** Mark an entry (workflow or system) as reversed by another. */
export function markReversed(id: string, reversedBy: string): void {
  for (const list of [WORKFLOW, SYSTEM]) {
    const e = list.find((x) => x.id === id);
    if (e) e.reversed_by = reversedBy;
  }
}

/* --------------------------------- audit --------------------------------- */
export function recordAudit(ev: Omit<AuditEvent, 'id' | 'at'> & { at?: string }): void {
  auditSeq += 1;
  AUDIT.unshift({
    ...ev,
    id: `aud-${auditSeq}`,
    at: ev.at ?? new Date().toISOString(),
    before: ev.before === undefined ? null : JSON.parse(JSON.stringify(ev.before)),
    after: ev.after === undefined ? null : JSON.parse(JSON.stringify(ev.after)),
  });
}
export function listAudit(): AuditEvent[] {
  return AUDIT.map((a) => ({ ...a }));
}

function clone<T>(v: T): T {
  return JSON.parse(JSON.stringify(v)) as T;
}
