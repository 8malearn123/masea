-- الوحدات الإدارية لها (مطابق لـ GRANTS.worker = {} في الواجهة).
-- ملاحظة: ربط حساب العاملة بملفها وسياسات RLS لقراءة بياناتها هي فقط تأتي
-- عند تفعيل البوابة على البيانات الحقيقية — الواجهة اليوم تعمل بالعرض التجريبي.
