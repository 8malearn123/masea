-- المبيعات الفعلية تُسحب تلقائيًا من العقود — لا إدخال يدوي:
--   • sales: صف واحد لكل عقد (contract_id فريد) يُنشئه مشغّل عند وصول العقد
--     لحالة البيع المعتمدة (موقّع / نشط / موقّع على مساند)، بمبالغ مجمّدة لحظة
--     البيع والموظف المسؤول وكوبون الخصم. لا يُحتسب العقد مرتين.
--   • العقد المكتمل ← البيع «مكتمل»؛ العقد الملغى ← البيع «ملغى» (لا يُحذف).
--   • sale_notes: ملاحظات على كل عملية بيع (سجل إضافي لا يُعدَّل).
--   • RLS: وحدة sales_ops + نطاق الفرع؛ موظف المبيعات يرى مبيعاته فقط.
-- الفاتورة (invoices) مستند محاسبي؛ البيع حدث تجاري — لا تكرار لمفهوم قائم.
-- التراجع: supabase/rollback/0063_sales_down.sql
-- =============================================================

create table if not exists sales (
  id              uuid primary key default gen_random_uuid(),
  sale_no         bigint generated by default as identity unique,
  contract_id     uuid not null unique references contracts(id) on delete restrict,
  quote_id        uuid references quotes(id) on delete set null,
  customer_id     uuid references customers(id) on delete set null,
  branch_id       uuid references branches(id) on delete set null,
  service_code    text references services(code),
  worker_name     text,
  gross_amount    numeric(12,2) not null default 0,   -- قيمة العقد قبل الخصم
  discount_amount numeric(12,2) not null default 0,
  net_amount      numeric(12,2) not null default 0,   -- صافي البيع قبل الضريبة
  vat_amount      numeric(12,2) not null default 0,
  total_amount    numeric(12,2) not null default 0,   -- شامل الضريبة
  promotion_id    uuid references promotions(id) on delete set null,
  coupon_code     text,
  is_renewal      boolean not null default false,
  sold_at         timestamptz not null default now(),
  sold_by         uuid references auth.users(id) on delete set null,
  sold_by_name    text,
  status          text not null default 'confirmed' check (status in ('confirmed','completed','cancelled')),
  cancelled_at    timestamptz,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists idx_sales_branch_date on sales(branch_id, sold_at desc);
create index if not exists idx_sales_sold_by on sales(sold_by);
create index if not exists idx_sales_service on sales(service_code);

create table if not exists sale_notes (
  id              uuid primary key default gen_random_uuid(),
  sale_id         uuid not null references sales(id) on delete cascade,
  note            text not null check (length(btrim(note)) >= 2),
  created_by      uuid references auth.users(id) on delete set null default auth.uid(),
  created_by_name text,
  created_at      timestamptz not null default now()
);
create index if not exists idx_sale_notes_sale on sale_notes(sale_id, created_at);

-- the statuses a contract counts as a sale at (managed in one place)
create or replace function contract_is_sold(p_status text)
returns boolean language sql immutable as
$$ select p_status in ('signed','active','musaned_signed','completed') $$;

-- ---------- the contract → sale link ----------------------------------------
create or replace function sync_sale_from_contract()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  v_quote   quotes;
  v_seller  uuid;
  v_status  text;
begin
  if contract_is_sold(new.status::text) then
    select * into v_quote from quotes where id = new.quote_id;
    v_seller := coalesce(v_quote.assigned_to, new.created_by);
    insert into sales (contract_id, quote_id, customer_id, branch_id, service_code, worker_name,
                       gross_amount, discount_amount, net_amount, vat_amount, total_amount,
                       promotion_id, coupon_code, is_renewal, sold_at, sold_by, sold_by_name, status)
    values (new.id, new.quote_id, new.customer_id, new.branch_id, new.service_code,
            coalesce(v_quote.worker_name, (select full_name from workers where id = new.worker_id)),
            coalesce(new.gross_amount, new.base_amount), coalesce(new.discount_amount, 0),
            new.base_amount, new.vat_amount, new.total_amount,
            new.promotion_id,
            coalesce(v_quote.coupon_code, (select upper(code) from promotions where id = new.promotion_id and requires_code)),
            new.parent_contract_id is not null,
            coalesce(new.signed_at, now()), v_seller,
            (select full_name from user_profiles where id = v_seller),
            case when new.status::text = 'completed' then 'completed' else 'confirmed' end)
    on conflict (contract_id) do nothing;   -- never counted twice
  end if;

  v_status := case new.status::text when 'completed' then 'completed'
                                    when 'cancelled' then 'cancelled' end;
  if v_status is not null then
    update sales set status = v_status,
                     cancelled_at = case when v_status = 'cancelled' then now() else cancelled_at end,
                     updated_at = now()
     where contract_id = new.id and status <> v_status;
  end if;
  return new;
end $$;

drop trigger if exists trg_contract_sale on contracts;
create trigger trg_contract_sale after insert or update of status on contracts
  for each row execute function sync_sale_from_contract();

-- backfill: contracts already sold before this migration (amounts as stored)
insert into sales (contract_id, quote_id, customer_id, branch_id, service_code,
                   gross_amount, discount_amount, net_amount, vat_amount, total_amount,
                   promotion_id, is_renewal, sold_at, sold_by, sold_by_name, status)
select c.id, c.quote_id, c.customer_id, c.branch_id, c.service_code,
       coalesce(c.gross_amount, c.base_amount), coalesce(c.discount_amount, 0),
       c.base_amount, c.vat_amount, c.total_amount, c.promotion_id,
       c.parent_contract_id is not null, coalesce(c.signed_at, c.created_at),
       c.created_by, (select full_name from user_profiles where id = c.created_by),
       case when c.status::text = 'completed' then 'completed' else 'confirmed' end
  from contracts c
 where contract_is_sold(c.status::text)
on conflict (contract_id) do nothing;

-- ---------- notes ---------------------------------------------------------------
create or replace function sale_notes_stamp() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.created_by := auth.uid();
  new.created_by_name := (select full_name from user_profiles where id = auth.uid());
  return new;
end $$;
drop trigger if exists trg_sale_notes_stamp on sale_notes;
create trigger trg_sale_notes_stamp before insert on sale_notes
  for each row execute function sale_notes_stamp();

create or replace function sale_notes_immutable() returns trigger
language plpgsql as $$ begin raise exception 'ملاحظات البيع سجل لا يُعدَّل — أضف ملاحظة جديدة'; end; $$;
drop trigger if exists trg_sale_notes_immutable on sale_notes;
create trigger trg_sale_notes_immutable before update or delete on sale_notes
  for each row execute function sale_notes_immutable();

-- ---------- RLS ------------------------------------------------------------------
alter table sales      enable row level security;
alter table sale_notes enable row level security;

create or replace function can_view_sale(p_branch uuid, p_seller uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select has_perm('sales_ops','view') and in_my_branch(p_branch)
     and (get_my_role() <> 'sales' or p_seller = auth.uid())
$$;
grant execute on function can_view_sale(uuid, uuid) to authenticated;

drop policy if exists sales_read on sales;
create policy sales_read on sales for select to authenticated
  using (can_view_sale(branch_id, sold_by));
-- no insert/update/delete policies: sales are written by the contract trigger only

drop policy if exists sale_notes_read on sale_notes;
create policy sale_notes_read on sale_notes for select to authenticated using (
  exists (select 1 from sales s where s.id = sale_notes.sale_id and can_view_sale(s.branch_id, s.sold_by))
);
drop policy if exists sale_notes_insert on sale_notes;
create policy sale_notes_insert on sale_notes for insert to authenticated with check (
  exists (select 1 from sales s where s.id = sale_notes.sale_id
          and can_view_sale(s.branch_id, s.sold_by)
          and (has_perm('sales_ops','edit') or s.sold_by = auth.uid()))
);

