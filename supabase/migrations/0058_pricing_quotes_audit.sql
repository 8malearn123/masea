-- ---------- 1) quotes --------------------------------------------------------
alter table quotes add column if not exists quote_no bigint generated by default as identity;
alter table quotes add column if not exists customer_name text;
alter table quotes add column if not exists customer_phone text;
alter table quotes add column if not exists nationality text;
alter table quotes add column if not exists profession text;
alter table quotes add column if not exists quantity integer not null default 1 check (quantity >= 1);
alter table quotes add column if not exists price_snapshot jsonb;
alter table quotes add column if not exists sent_at timestamptz;
alter table quotes add column if not exists decided_at timestamptz;
alter table quotes add column if not exists parent_id uuid references quotes(id) on delete set null;
create unique index if not exists ux_quotes_quote_no on quotes(quote_no);

-- the snapshot is frozen once written
create or replace function quotes_snapshot_immutable() returns trigger
language plpgsql as $$
begin
  if old.price_snapshot is not null and new.price_snapshot is distinct from old.price_snapshot then
    raise exception 'نسخة حساب عرض السعر ثابتة ولا تُعدّل — أنشئ نسخة جديدة من العرض';
  end if;
  if old.price_snapshot is not null and (new.total_amount <> old.total_amount
      or new.base_amount <> old.base_amount or new.vat_amount <> old.vat_amount) then
    raise exception 'مبالغ عرض السعر ثابتة بعد الإنشاء';
  end if;
  return new;
end;
$$;
drop trigger if exists trg_quotes_snapshot on quotes;
create trigger trg_quotes_snapshot before update on quotes
  for each row execute function quotes_snapshot_immutable();

-- pricing users can read quotes too (writes go through the functions below)
drop policy if exists quotes_pricing_read on quotes;
create policy quotes_pricing_read on quotes for select to authenticated using (
  has_perm('pricing', 'view') and (is_cross_branch() or branch_id = get_my_branch())
);

-- ---------- 2) quote_events ---------------------------------------------------
create table if not exists quote_events (
  id        bigint generated always as identity primary key,
  quote_id  uuid not null references quotes(id) on delete cascade,
  type      text not null check (type in ('created','whatsapp_opened','marked_sent','pdf_generated',
                                          'accepted','rejected','expired','version_created','converted')),
  at        timestamptz not null default now(),
  actor     uuid references auth.users(id) on delete set null,
  note      text
);
create index if not exists idx_quote_events_quote on quote_events(quote_id, at);

create or replace function quote_events_immutable() returns trigger
language plpgsql as $$ begin raise exception 'سجل أحداث العرض غير قابل للتعديل'; end; $$;
drop trigger if exists trg_quote_events_immutable on quote_events;
create trigger trg_quote_events_immutable before update or delete on quote_events
  for each row execute function quote_events_immutable();

alter table quote_events enable row level security;
drop policy if exists qev_read on quote_events;
create policy qev_read on quote_events for select to authenticated using (
  exists (select 1 from quotes q where q.id = quote_events.quote_id)   -- inherits quotes RLS
);
drop policy if exists qev_insert on quote_events;
create policy qev_insert on quote_events for insert to authenticated with check (
  actor = auth.uid()
  and type in ('whatsapp_opened','pdf_generated')            -- UI-only events; the rest via functions
  and exists (select 1 from quotes q where q.id = quote_events.quote_id)
);

-- ---------- 3) create a quote from a server-side price ----------------------
create or replace function create_quote_from_price(
  p_service_code text,
  p_params jsonb,
  p_customer_name text,
  p_customer_phone text,
  p_valid_until date,
  p_notes text default null,
  p_parent_id uuid default null,
  p_snapshot jsonb default null
) returns quotes
language plpgsql security definer set search_path = public as $$
declare
  v_price jsonb;
  v_row   quotes;
begin
  if not (has_perm('pricing','create') or has_perm('leads','create')) then
    raise exception 'لا تملك صلاحية إنشاء عروض الأسعار';
  end if;
  if length(btrim(coalesce(p_customer_name, ''))) < 3 then raise exception 'اسم العميل مطلوب'; end if;
  if p_valid_until is null or p_valid_until <= current_date then raise exception 'تاريخ صلاحية العرض يجب أن يكون لاحقًا لليوم'; end if;

  -- the backend price is authoritative (same engine as contracts)
  v_price := calc_price(p_service_code, p_params);
  if (v_price->>'base')::numeric <= 0 then raise exception 'لا توجد قاعدة سعر نشطة لهذه الخدمة'; end if;
  if not coalesce((v_price->>'promotion_ok')::boolean, true) then
    raise exception 'الخصم غير قابل للتطبيق: %', coalesce(v_price->>'promotion_reason', '');
  end if;
  if (v_price->>'total')::numeric <= 0 then raise exception 'الإجمالي غير صالح'; end if;

  insert into quotes (service_code, customer_name, customer_phone, nationality, profession, quantity,
                      base_amount, vat_amount, total_amount, status, valid_until, notes,
                      assigned_to, branch_id, created_by, parent_id, price_snapshot)
  values (p_service_code, btrim(p_customer_name), nullif(btrim(coalesce(p_customer_phone,'')), ''),
          nullif(p_params->>'nationality',''), nullif(p_params->>'profession',''),
          greatest(coalesce((p_params->>'quantity')::integer, 1), 1),
          (v_price->>'net')::numeric, (v_price->>'vat')::numeric, (v_price->>'total')::numeric,
          'draft', p_valid_until, p_notes, auth.uid(), get_my_branch(), auth.uid(), p_parent_id,
          coalesce(p_snapshot, '{}'::jsonb)
            || jsonb_build_object('server', v_price, 'params', p_params, 'computed_at', now()))
  returning * into v_row;

  insert into quote_events (quote_id, type, actor, note)
  values (v_row.id, case when p_parent_id is null then 'created' else 'version_created' end, auth.uid(), null);

  -- tag the calc_price log row written in this same transaction
  update pricing_log set op_type = 'quote', reference = 'QT-' || v_row.quote_no
  where id = (select id from pricing_log
              where created_at = now() and created_by is not distinct from auth.uid()
              order by created_at desc limit 1);
  return v_row;
end;
$$;

-- ---------- 4) guarded status transitions -----------------------------------
create or replace function set_quote_status(p_quote_id uuid, p_status text, p_note text default null)
returns quotes language plpgsql security definer set search_path = public as $$
declare v_row quotes; v_from text;
begin
  if not (has_perm('pricing','edit') or has_perm('leads','edit')) then
    raise exception 'لا تملك صلاحية تحديث العروض';
  end if;
  select * into v_row from quotes where id = p_quote_id for update;
  if v_row.id is null then raise exception 'العرض غير موجود'; end if;
  v_from := case when v_row.status in ('draft','sent') and v_row.valid_until < current_date
                 then 'expired' else v_row.status end;
  if not ((v_from = 'draft' and p_status in ('sent','accepted','rejected'))
       or (v_from = 'sent'  and p_status in ('accepted','rejected'))) then
    raise exception 'لا يمكن نقل العرض من «%» إلى «%»', v_from, p_status;
  end if;
  update quotes set status = p_status,
         sent_at = case when p_status = 'sent' then now() else sent_at end,
         decided_at = case when p_status in ('accepted','rejected') then now() else decided_at end
  where id = p_quote_id returning * into v_row;
  insert into quote_events (quote_id, type, actor, note)
  values (p_quote_id, case p_status when 'sent' then 'marked_sent' else p_status end, auth.uid(), p_note);
  return v_row;
end;
$$;

-- ---------- 5) price-change history -----------------------------------------
alter table pricing_rules add column if not exists updated_at timestamptz not null default now();
alter table pricing_rules add column if not exists updated_by uuid references auth.users(id) on delete set null;

create table if not exists pricing_rule_changes (
  id             bigint generated always as identity primary key,
  rule_id        uuid not null references pricing_rules(id) on delete cascade,
  old_base       numeric(12,2),
  new_base       numeric(12,2) not null,
  old_min        numeric(12,2),
  new_min        numeric(12,2),
  effective_from date not null,
  reason         text not null check (length(btrim(reason)) >= 5),
  changed_by     uuid references auth.users(id) on delete set null,
  changed_by_name text,
  changed_at     timestamptz not null default now()
);
create index if not exists idx_rule_changes_rule on pricing_rule_changes(rule_id, changed_at desc);
alter table pricing_rule_changes enable row level security;
drop policy if exists prc_read on pricing_rule_changes;
create policy prc_read on pricing_rule_changes for select to authenticated using (has_perm('pricing','view'));
create or replace function pricing_rule_changes_immutable() returns trigger
language plpgsql as $$ begin raise exception 'سجل تعديلات الأسعار غير قابل للتعديل'; end; $$;
drop trigger if exists trg_prc_immutable on pricing_rule_changes;
create trigger trg_prc_immutable before update or delete on pricing_rule_changes
  for each row execute function pricing_rule_changes_immutable();

create or replace function change_pricing_rule(
  p_rule_id uuid, p_base numeric, p_min numeric, p_effective_from date, p_reason text
) returns pricing_rules language plpgsql security definer set search_path = public as $$
declare v_old pricing_rules; v_new pricing_rules;
begin
  if not has_perm('pricing','edit') then raise exception 'لا تملك صلاحية تعديل الأسعار'; end if;
  if p_base is null or p_base <= 0 then raise exception 'السعر الأساسي يجب أن يكون أكبر من صفر'; end if;
  if p_min is not null and (p_min < 0 or p_min > p_base) then raise exception 'الحد الأدنى بين صفر والسعر الأساسي'; end if;
  if length(btrim(coalesce(p_reason,''))) < 5 then raise exception 'سبب التعديل مطلوب'; end if;
  if p_effective_from is null or p_effective_from < current_date then raise exception 'تاريخ السريان لا يسبق اليوم'; end if;
  select * into v_old from pricing_rules where id = p_rule_id for update;
  if v_old.id is null then raise exception 'القاعدة غير موجودة'; end if;
  update pricing_rules set base_price = p_base, min_price = p_min, updated_at = now(), updated_by = auth.uid()
  where id = p_rule_id returning * into v_new;
  insert into pricing_rule_changes (rule_id, old_base, new_base, old_min, new_min, effective_from, reason, changed_by, changed_by_name)
  values (p_rule_id, v_old.base_price, p_base, v_old.min_price, p_min, p_effective_from, btrim(p_reason), auth.uid(),
          (select full_name from user_profiles where id = auth.uid()));
  return v_new;
end;
$$;

-- ---------- 6) config & log attribution --------------------------------------
alter table pricing_config add column if not exists updated_by uuid references auth.users(id) on delete set null;
alter table pricing_config add column if not exists updated_by_name text;
create or replace function pricing_config_stamp() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  new.updated_by_name := (select full_name from user_profiles where id = auth.uid());
  return new;
end;
$$;
drop trigger if exists trg_pricing_config_stamp on pricing_config;
create trigger trg_pricing_config_stamp before update on pricing_config
  for each row execute function pricing_config_stamp();

-- historical rows keep NULL (never back-filled); new rows are attributed
alter table pricing_log add column if not exists op_type text check (op_type in ('calculation','quote','contract'));
alter table pricing_log add column if not exists reference text;
alter table pricing_log add column if not exists user_name text;
create or replace function pricing_log_stamp() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.op_type := coalesce(new.op_type, 'calculation');
  new.user_name := coalesce(new.user_name, (select full_name from user_profiles where id = new.created_by));
  return new;
end;
$$;
drop trigger if exists trg_pricing_log_stamp on pricing_log;
create trigger trg_pricing_log_stamp before insert on pricing_log
  for each row execute function pricing_log_stamp();

