--  1. quotes: customer/service fields that were never persisted, an immutable
--     price snapshot, lifecycle timestamps, version link, human quote number.
--  2. quote_events: append-only history (created / whatsapp_opened /
--     marked_sent / pdf / accepted / rejected / expired / version / converted).
--     A WhatsApp link opening is recorded as such — never as "delivered".
--  3. create_quote_from_price(): recomputes via calc_price server-side,
--     refuses quotes that break the rules, stores the snapshot.
--  4. set_quote_status(): guarded transitions (decisions are final).
--  5. pricing_rule_changes + change_pricing_rule(): reason & effective date
--     recorded; existing quotes/contracts keep their stored amounts.
--  6. pricing_config / pricing_log: who changed / operation type / reference.
